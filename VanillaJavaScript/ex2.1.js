// Function that takes two numbers as parameters and returns their sum
function addNumbers(num1, num2)
{
    return num1 + num2;
}

// Test the function with different numbers
console.log("Sum of 5 and 3:", addNumbers(5, 3));
console.log("Sum of 10 and 20:", addNumbers(10, 20));
console.log("Sum of -5 and 8:", addNumbers(-5, 8));
console.log("Sum of 0 and 0:", addNumbers(0, 0));
console.log("Sum of 3.5 and 2.7:", addNumbers(3.5, 2.7));
